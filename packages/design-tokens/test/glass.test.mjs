// TOK1 (TS-DSK-001 T004): glass.css is generated from tokens/glass.json, both themes are complete and
// consistent, and the colours meet the WCAG contrast of DSYS-GRP-002 § 3, § 4 and § 10.
import assert from 'node:assert/strict';
import { cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { DEFAULT_TOKENS_DIR, isUpToDate } from '../scripts/build.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const readCss = () => readFile(path.join(root, 'css', 'glass.css'), 'utf8');
const readGlass = async (dir = DEFAULT_TOKENS_DIR) => JSON.parse(await readFile(path.join(dir, 'glass.json'), 'utf8'));

/** Leaf tokens (objects with `$value`) as `[dottedPath, token]`. */
function leaves(node, prefix = []) {
  if (node && typeof node === 'object' && '$value' in node) return [[prefix.join('.'), node]];
  return Object.entries(node ?? {})
    .filter(([k]) => !k.startsWith('$'))
    .flatMap(([k, v]) => leaves(v, [...prefix, k]));
}

/** Body of the block opened by the first selector that starts with `head`, with balanced braces. */
function block(css, head) {
  const start = css.indexOf(head);
  assert.notEqual(start, -1, `glass.css has no block starting with ${head}`);
  const open = css.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1;
    if (css[i] === '}') depth -= 1;
    if (depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`unbalanced block ${head}`);
}

function vars(body) {
  const out = new Map();
  for (const m of body.matchAll(/(--gr-[a-z0-9-]+)\s*:\s*([^;]*);/g)) out.set(m[1], m[2].trim());
  return out;
}

const themes = async () => {
  const css = await readCss();
  const dark = vars(block(css, ':root {'));
  const light = vars(block(css, ':root[data-theme="light"]'));
  const media = block(css, '@media (prefers-color-scheme: light)');
  const auto = vars(block(media, ':root:not([data-theme="dark"])'));
  return { css, dark, light, auto };
};

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const f = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const isHex = (v) => /^#[0-9a-f]{6}$/i.test(v ?? '');
const SURFACES = ['window', 'panel', 'control', 'raised', 'hover'];

test('TOK1: glass.css exists with the generated header and three theme blocks', async () => {
  const { css } = await themes();
  assert.ok(css.startsWith('/* Generated by @gitraptor/tokens from tokens/glass.json. Do not edit. */'), 'missing generated header');
  assert.match(css, /color-scheme:\s*dark/);
  assert.match(css, /:root\[data-theme="light"\]\s*\{\s*color-scheme:\s*light/);
  assert.match(css, /@media \(prefers-color-scheme: light\)\s*\{\s*:root:not\(\[data-theme="dark"\]\)/);
});

test('TOK1: every glass colour token declares a light value', async () => {
  const glass = await readGlass();
  const colours = leaves(glass.glass).filter(([, t]) => t.$type === 'color');
  assert.ok(colours.length > 20, 'glass.json should carry the colour tables of DSYS-GRP-002');
  for (const [name, token] of colours) {
    assert.ok(token.$extensions?.['dev.gitraptor']?.light, `glass.${name} has no $extensions["dev.gitraptor"].light`);
  }
});

test('TOK1: surface-window is #26282d in :root and #e6e8ec in both light blocks', async () => {
  const { dark, light, auto } = await themes();
  assert.equal(dark.get('--gr-surface-window'), '#26282d');
  assert.equal(light.get('--gr-surface-window'), '#e6e8ec');
  assert.equal(auto.get('--gr-surface-window'), '#e6e8ec');
});

test('TOK1: the two light blocks are identical', async () => {
  const { light, auto } = await themes();
  assert.ok(light.size > 20, 'the light block is empty');
  assert.deepEqual([...auto], [...light], 'data-theme="light" and prefers-color-scheme blocks differ');
});

test('TOK1: no variable is empty and the light block overrides only names of :root', async () => {
  const { dark, light } = await themes();
  assert.ok(dark.size > 50, ':root should declare every glass token');
  for (const map of [dark, light]) {
    for (const [name, value] of map) assert.notEqual(value, '', `${name} is empty`);
  }
  for (const name of light.keys()) assert.ok(dark.has(name), `${name} is in the light block but not in :root`);
});

test('TOK1: text and *.text colours reach 4.5:1 on every surface in both themes', async () => {
  const { dark, light } = await themes();
  for (const [theme, map] of [['dark', dark], ['light', light]]) {
    const resolve = (name) => map.get(name) ?? dark.get(name);
    const texts = [...dark.keys()].filter(
      (n) => (/^--gr-text-(main|muted|faint)$/.test(n) || /-text$/.test(n)) && !/on-accent|disabled/.test(n),
    );
    assert.ok(texts.length >= 9, `expected text.* and *.text tokens, found ${texts.length}`);
    for (const t of texts) {
      for (const s of SURFACES) {
        // DSYS-GRP-002 § 3: dark text.faint does not go on raised nor hover
        if (theme === 'dark' && t === '--gr-text-faint' && (s === 'raised' || s === 'hover')) continue;
        const fg = resolve(t);
        const bg = resolve(`--gr-surface-${s}`);
        if (!isHex(fg) || !isHex(bg)) continue;
        assert.ok(ratio(fg, bg) >= 4.5, `${theme}: ${t} on ${s} is ${ratio(fg, bg).toFixed(2)}:1 (< 4.5)`);
      }
    }
  }
});

test('TOK1: fill colours reach 3:1 on panel and control in both themes', async () => {
  const { dark, light } = await themes();
  const fills = ['accent', 'success', 'warning', 'danger', 'agent-claude'].map((n) => `--gr-${n}`);
  for (const [theme, map] of [['dark', dark], ['light', light]]) {
    const resolve = (name) => map.get(name) ?? dark.get(name);
    for (const f of fills) {
      for (const s of ['panel', 'control']) {
        const fg = resolve(f);
        const bg = resolve(`--gr-surface-${s}`);
        assert.ok(isHex(fg), `${theme}: ${f} is not an opaque hex (${fg})`);
        assert.ok(ratio(fg, bg) >= 3, `${theme}: ${f} on ${s} is ${ratio(fg, bg).toFixed(2)}:1 (< 3)`);
      }
    }
  }
});

test('TOK1: check detects a glass.css out of date with glass.json', async () => {
  const dir = await mkdtemp(path.join(tmpdir(), 'gitraptor-glass-test-'));
  try {
    await cp(DEFAULT_TOKENS_DIR, path.join(dir, 'tokens'), { recursive: true });
    const file = path.join(dir, 'tokens', 'glass.json');
    const glass = await readGlass(path.join(dir, 'tokens'));
    glass.glass.surface.window.$value = '#010203';
    await writeFile(file, JSON.stringify(glass));
    assert.equal(await isUpToDate({ tokensDir: path.join(dir, 'tokens') }), false, 'an edited glass.json must make check fail');
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
