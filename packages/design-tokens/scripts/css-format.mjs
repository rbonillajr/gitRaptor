// Style Dictionary format that writes `css/glass.css` (ADR-GRP-003, Enmienda 2026-11-08; DSYS-GRP-002 § 9).
//
// Every `glass.*` token becomes `--gr-<path in kebab>` in `:root` (dark, or the only value); the ones
// with a light value are repeated in `:root[data-theme="light"]` and in the `prefers-color-scheme: light`
// block that applies when the user left the theme on `auto`. Values are written literally.
//
// Two bounded blocks follow, `[data-theme="dark"]` and `[data-theme="light"]` (TS-DSK-003, D5): they pin a
// subtree to one theme whatever `<html>` says, so they carry only the tokens that change per theme (a light
// value, or a value that references another variable). Sizes, spacing, radii, motion and z do not change.

const EXT = 'dev.gitraptor';
const HEADER = '/* Generated by @gitraptor/tokens from tokens/glass.json. Do not edit. */';

const kebab = (segment) =>
  String(segment)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();

/** `glass.accent.DEFAULT` -> `--gr-accent`; `glass.agent.claude.text` -> `--gr-agent-claude-text`. */
export function cssName(path) {
  const rest = path.slice(1);
  if (rest[rest.length - 1] === 'DEFAULT') rest.pop();
  return `--gr-${rest.map(kebab).join('-')}`;
}

const lightOf = (token) => token.original?.$extensions?.[EXT]?.light ?? token.$extensions?.[EXT]?.light;
const valueOf = (token) => token.original?.$value ?? token.$value;

/** Builds the CSS source from the dictionary. Pure: same tokens, same bytes. */
export function renderCss(dictionary) {
  const tokens = dictionary.allTokens;
  const dark = tokens.map((t) => `  ${cssName(t.path)}: ${valueOf(t)};`);
  const light = tokens.filter((t) => lightOf(t) !== undefined).map((t) => `${cssName(t.path)}: ${lightOf(t)};`);
  const themed = tokens.filter((t) => lightOf(t) !== undefined || String(valueOf(t)).includes('var(') || String(lightOf(t) ?? '').includes('var('));
  const boundedDark = themed.map((t) => `  ${cssName(t.path)}: ${valueOf(t)};`);
  const boundedLight = themed.map((t) => `  ${cssName(t.path)}: ${lightOf(t) ?? valueOf(t)};`);
  return [
    HEADER,
    '',
    ':root {',
    '  color-scheme: dark;',
    ...dark,
    '}',
    '',
    ':root[data-theme="light"] {',
    '  color-scheme: light;',
    ...light.map((l) => `  ${l}`),
    '}',
    '',
    '@media (prefers-color-scheme: light) {',
    '  :root:not([data-theme="dark"]) {',
    '    color-scheme: light;',
    ...light.map((l) => `    ${l}`),
    '  }',
    '}',
    '',
    '[data-theme="dark"] {',
    '  color-scheme: dark;',
    ...boundedDark,
    '}',
    '',
    '[data-theme="light"] {',
    '  color-scheme: light;',
    ...boundedLight,
    '}',
    '',
  ].join('\n');
}
