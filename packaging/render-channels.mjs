// Renders the distribution channels of a release (INF-GRP-004, ADR-GRP-014 § 5) from the built
// archives and SHA256SUMS: the Homebrew formula, the winget manifests and the npm packages.
// It only writes files under --out; it never publishes anything.
//
//   node packaging/render-channels.mjs --version 0.1.0 --dist dist --out channels \
//     [--repo rbonillajr/gitRaptor]
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const here = path.dirname(fileURLToPath(import.meta.url));
const { values: args } = parseArgs({
  options: {
    version: { type: "string" },
    dist: { type: "string" },
    out: { type: "string" },
    repo: { type: "string", default: "rbonillajr/gitRaptor" },
  },
});
for (const name of ["version", "dist", "out"]) {
  if (!args[name]) throw new Error(`--${name} is required`);
}
const { version, repo } = args;
const dist = path.resolve(args.dist);
const out = path.resolve(args.out);

// Rust target → channel names. Linux is a static musl build, valid on glibc and musl alike.
const TARGETS = [
  { target: "x86_64-unknown-linux-musl", os: "linux", cpu: "x64", ext: "tar.gz" },
  { target: "aarch64-unknown-linux-musl", os: "linux", cpu: "arm64", ext: "tar.gz" },
  { target: "x86_64-apple-darwin", os: "darwin", cpu: "x64", ext: "tar.gz" },
  { target: "aarch64-apple-darwin", os: "darwin", cpu: "arm64", ext: "tar.gz" },
  { target: "x86_64-pc-windows-msvc", os: "win32", cpu: "x64", ext: "zip" },
  { target: "aarch64-pc-windows-msvc", os: "win32", cpu: "arm64", ext: "zip" },
];

const license = (() => {
  const toml = readFileSync(path.join(here, "..", "Cargo.toml"), "utf8");
  return /^\s*license\s*=\s*"([^"]+)"/m.exec(toml)?.[1] ?? "UNLICENSED";
})();

const sums = new Map(
  readFileSync(path.join(dist, "SHA256SUMS"), "utf8")
    .split("\n")
    .filter((l) => l.trim() !== "")
    .map((l) => {
      const [hash, file] = l.trim().split(/\s+/);
      return [file.replace(/^\*/, ""), hash.toLowerCase()];
    }),
);

const assets = TARGETS.map((t) => {
  const file = `raptor-${version}-${t.target}.${t.ext}`;
  const sha256 = sums.get(file);
  if (!sha256) throw new Error(`${file} is missing from SHA256SUMS`);
  return { ...t, file, sha256, url: `https://github.com/${repo}/releases/download/v${version}/${file}` };
});
const asset = (os, cpu) => assets.find((a) => a.os === os && a.cpu === cpu);

function write(rel, content, mode) {
  const file = path.join(out, rel);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  if (mode) chmodSync(file, mode);
  return file;
}

// --- Homebrew (own tap). The formula is `gitraptor`: homebrew-core already has a `raptor`
// formula (the RDF library). No `service` block: autostart is only `raptor daemon enable` (PQ-1).
function homebrew() {
  const block = (os, cpu) => {
    const a = asset(os, cpu);
    return `      url "${a.url}"\n      sha256 "${a.sha256}"`;
  };
  const licenseLine =
    license === "UNLICENSED"
      ? "  # license: pending decision (open question 2); required before publishing the tap."
      : `  license "${license}"`;
  return write(
    "homebrew/Formula/gitraptor.rb",
    `# Generated by packaging/render-channels.mjs for v${version}. Do not edit by hand.
class Gitraptor < Formula
  desc "Git copilot for teams that code with AI agents"
  homepage "https://github.com/${repo}"
  version "${version}"
${licenseLine}

  on_macos do
    on_arm do
${block("darwin", "arm64")}
    end
    on_intel do
${block("darwin", "x64")}
    end
  end

  on_linux do
    on_arm do
${block("linux", "arm64")}
    end
    on_intel do
${block("linux", "x64")}
    end
  end

  def install
    bin.install "raptor", "raptor-mcp"
  end

  test do
    assert_equal "raptor #{version}", shell_output("#{bin}/raptor --version").strip
  end
end
`,
  );
}

// --- winget: multi-file manifest, zip with two portable nested installers.
function winget() {
  const id = "GitRaptor.GitRaptor";
  const dir = `winget/manifests/g/GitRaptor/GitRaptor/${version}`;
  const manifestVersion = "1.9.0";
  const header = (type) =>
    `# Generated by packaging/render-channels.mjs for v${version}. Do not edit by hand.\n` +
    `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${manifestVersion}.schema.json\n`;
  write(
    `${dir}/${id}.yaml`,
    `${header("version")}PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${manifestVersion}
`,
  );
  // Each architecture's zip holds its own top folder, so the nested files are per installer.
  const installers = ["x64", "arm64"]
    .map((cpu) => {
      const a = asset("win32", cpu);
      const folder = `raptor-${version}-${a.target}`;
      return `  - Architecture: ${cpu}
    InstallerUrl: ${a.url}
    InstallerSha256: ${a.sha256.toUpperCase()}
    NestedInstallerFiles:
      - RelativeFilePath: ${folder}\\raptor.exe
        PortableCommandAlias: raptor
      - RelativeFilePath: ${folder}\\raptor-mcp.exe
        PortableCommandAlias: raptor-mcp`;
    })
    .join("\n");
  write(
    `${dir}/${id}.installer.yaml`,
    `${header("installer")}PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
Commands:
  - raptor
  - raptor-mcp
Installers:
${installers}
ManifestType: installer
ManifestVersion: ${manifestVersion}
`,
  );
  write(
    `${dir}/${id}.locale.en-US.yaml`,
    `${header("defaultLocale")}PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: GitRaptor
PackageName: GitRaptor
PackageUrl: https://github.com/${repo}
License: ${license}
ShortDescription: Git copilot for teams that code with AI agents.
Moniker: raptor
ManifestType: defaultLocale
ManifestVersion: ${manifestVersion}
`,
  );
}

// --- npm: `gitraptor` plus one package per platform in optionalDependencies (ADR-GRP-014 § 5).
function npm() {
  const platformPkg = (a) => `@gitraptor/cli-${a.os}-${a.cpu}`;
  const platforms = Object.fromEntries(assets.map((a) => [`${a.os}-${a.cpu}`, platformPkg(a)]));
  const common = {
    version,
    license,
    homepage: `https://github.com/${repo}`,
    repository: { type: "git", url: `git+https://github.com/${repo}.git` },
  };
  const scratch = path.join(out, ".extract");
  for (const a of assets) {
    const name = platformPkg(a);
    const dir = path.join(out, "npm", `cli-${a.os}-${a.cpu}`);
    const tmp = path.join(scratch, a.target);
    mkdirSync(tmp, { recursive: true });
    const archive = path.join(dist, a.file);
    const r =
      a.ext === "zip"
        ? spawnSync("unzip", ["-q", "-o", archive, "-d", tmp], { stdio: "inherit" })
        : spawnSync("tar", ["-xzf", archive, "-C", tmp], { stdio: "inherit" });
    if (r.status !== 0) throw new Error(`could not extract ${a.file}`);
    const exe = a.os === "win32" ? ".exe" : "";
    mkdirSync(path.join(dir, "bin"), { recursive: true });
    for (const bin of ["raptor", "raptor-mcp"]) {
      const dest = path.join(dir, "bin", bin + exe);
      copyFileSync(path.join(tmp, `raptor-${version}-${a.target}`, bin + exe), dest);
      chmodSync(dest, 0o755);
    }
    write(
      path.relative(out, path.join(dir, "package.json")),
      `${JSON.stringify(
        {
          name,
          ...common,
          description: `GitRaptor native binaries for ${a.os}-${a.cpu} (${a.target})`,
          os: [a.os],
          cpu: [a.cpu],
          files: ["bin/"],
          preferUnplugged: true,
        },
        null,
        2,
      )}\n`,
    );
  }
  const launcher = readFileSync(path.join(here, "npm", "launcher.cjs"), "utf8").replace(
    "__PLATFORMS__",
    JSON.stringify(platforms, null, 2),
  );
  for (const bin of ["raptor", "raptor-mcp"]) {
    write(`npm/gitraptor/bin/${bin}.cjs`, launcher.replace("__BIN__", bin), 0o755);
  }
  write(
    "npm/gitraptor/package.json",
    `${JSON.stringify(
      {
        name: "gitraptor",
        ...common,
        description: "GitRaptor: Git copilot for teams that code with AI agents (raptor CLI/TUI and raptor-mcp)",
        bin: { raptor: "bin/raptor.cjs", "raptor-mcp": "bin/raptor-mcp.cjs" },
        files: ["bin/"],
        engines: { node: ">=18" },
        optionalDependencies: Object.fromEntries(Object.values(platforms).map((p) => [p, version])),
      },
      null,
      2,
    )}\n`,
  );
  write(
    "npm/gitraptor/README.md",
    `# gitraptor\n\nInstalls \`raptor\` and \`raptor-mcp\` ${version}. The native binary comes from the\n\`@gitraptor/cli-<os>-<cpu>\` package that matches this machine; nothing is downloaded at run time.\n`,
  );
  rmSync(scratch, { recursive: true, force: true });
}

homebrew();
winget();
npm();
console.log(`rendered channels for v${version} into ${out}`);
