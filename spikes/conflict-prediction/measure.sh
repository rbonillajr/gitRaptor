#!/usr/bin/env bash
# SPIKE-CKP-001 — final measurement, phase (b): run it with the machine at rest (no other
# builds or workers). Reproduces every experiment of the plan on macOS and writes the evidence
# to results/final-<date>/ . Takes about 1.5–2 h; nothing outside CKP_ROOT is written, except
# the results folder and the engine bench's cargo target.
#
#   ./measure.sh                 # everything
#   ./measure.sh --skip-engine   # without the E9 engine-p95 runs (the slowest part)
#
# Requirements: Rust, Python 3, network once (git/git clone), and ./setup-git.sh run once.
set -euo pipefail
cd "$(dirname "$0")"
export CKP_ROOT="${CKP_ROOT:-${TMPDIR:-/tmp}/ckp-spike-final}"
SKIP_ENGINE=0
[ "${1:-}" = "--skip-engine" ] && SKIP_ENGINE=1
STAMP=$(date -u +%Y-%m-%d)
FINAL="results/final-$STAMP"
mkdir -p "$CKP_ROOT" "$FINAL"
touch "$CKP_ROOT/.gitraptor-testkit-root"
echo "load before: $(uptime)" | tee "$FINAL/machine.txt"
{ sysctl -n machdep.cpu.brand_string; sysctl -n hw.ncpu; sysctl -n hw.memsize; sw_vers; } >> "$FINAL/machine.txt"

cargo build --release --quiet
( cd gix088 && cargo build --release --quiet )
[ -d "$CKP_ROOT/git.git" ] || git clone -q --bare https://github.com/git/git.git "$CKP_ROOT/git.git"
GIT_SRC="$CKP_ROOT/git.git" ./setup-git.sh
[ -f "$CKP_ROOT/ref-H/.git/HEAD" ] || ./target/release/ckp-spike gen-h "$CKP_ROOT/ref-H"

# Each suite writes into results/; move its output into the dated folder afterwards.
run() { local name=$1; shift; echo "== $name — load $(uptime | sed 's/.*averages*: //')"; "$@"; }
run E1  bash suites/e1-intact.sh 3
run E2-E4 bash suites/e2-e4-canary.sh
run E6-E7 bash suites/e6-e7-fidelity.sh 2000 100
run E8-E9 bash suites/e8-e9-perf.sh final 200 600
run E10 bash suites/e10-hostile.sh 20
mv results/e1-intact.* results/e2-e4-canary.tsv results/e6-e7-fidelity.txt results/e8-e9-perf-final.txt results/e10-hostile.txt "$FINAL/"

# H9: the same R-REAL run against gix 0.88 / gix-merge 0.21.
W="$CKP_ROOT/e6"
./gix088/target/release/ckp-spike-gix088 batch a2 "$CKP_ROOT/git.git" "$W/real-pairs.tsv" --hunks > "$W/real-a2-gix088.tsv"
python3 suites/lib/compare.py "$W/real-a2-gix088.tsv" "$W/real-a2.tsv" --diffs 20 > "$FINAL/h9-gix088-vs-gix089.txt"

# E9: the engine's p95 (t0 -> t_client_recv, INF-GRP-002 bench) alone, and with a predictor
# burst of 1 and 2 jobs running at the same time with QoS utility.
if [ "$SKIP_ENGINE" = 0 ]; then
  ROOT=$(cd ../.. && pwd)
  # The bench reuses the reference repo when `ref-H.done` exists (same seed and extra commit).
  echo "generated by ckp-spike gen-h" > "$CKP_ROOT/ref-H.done"
  F="$CKP_ROOT/perf-final"
  engine() { ( cd "$ROOT" && ENGINE_BENCH_ROOT="$CKP_ROOT" cargo bench -q -p gitraptor-cli --bench engine -- --gate reference ) ; }
  engine > "$FINAL/e9-engine-alone.txt" 2>&1 || true
  for jobs in 1 2; do
    ./target/release/ckp-spike bench burst "$F" --engine a2w --jobs "$jobs" --duration 1200 > "$FINAL/e9-burst-$jobs.txt" 2>&1 &
    BURST=$!
    engine > "$FINAL/e9-engine-with-burst-$jobs.txt" 2>&1 || true
    kill "$BURST" 2>/dev/null || true
    wait "$BURST" 2>/dev/null || true
  done
fi
echo "load after: $(uptime)" >> "$FINAL/machine.txt"
echo "done: $FINAL"
